def has_star(name: str) -> bool:
    """정본 테이블에 있는 주성인지(전수 커버 검증·fail-closed 판별용)."""
    return name in STAR_TEMPERAMENT


def brightness_level(brightness: str) -> str:
    """밝기 원시값 -> 등급 태그(bright/favor/dark). 중립(平閒不)·미상은 빈 문자열."""
    if brightness in _BRIGHT_BRIGHT:
        return "bright"
    if brightness in _BRIGHT_FAVOR:
        return "favor"
    if brightness in _BRIGHT_DARK:
        return "dark"
    return ""
